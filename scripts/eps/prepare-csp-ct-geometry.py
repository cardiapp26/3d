"""
Measure the CSP implant landmarks on the real chest CT of the cardiac CT studio
(public/ct-data/s0019, TotalSegmentator dataset, CC BY 4.0) and write them to
src/eps/csp/csp-ct-geometry.mjs, so the CSP console can draw the sheath and lead
inside that patient's heart under live fluoroscopy (csp-ct-xray.mjs).

Coordinates are millimetres in the stored voxel order: x patient right -> left,
y anterior -> posterior, z cranial -> caudal (voxel index times spacing).

Landmarks, all from the labels:
  tv       tricuspid valve centre: RV voxels touching the RA
  apex     RV apex: the RV voxel caudal of the valve farthest from it
  av       aortic valve centre: aorta voxels touching the LV
  his      RV septal surface point nearest the aortic valve (membranous septum)
  septum   RV and LV sides of the interventricular septum at 21 levels from the
           His (0) to the RV apex (1): the RV septal surface point nearest the
           His-apex line and the nearest LV cavity voxel to it
  ra, raTop, svc, highSvc, innominate   the venous route of the sheath (the SVC
           is not labelled: it is continued straight up from the RA roof)
  iso      isocentre: centre of the four chambers

Usage: python prepare-csp-ct-geometry.py [ct case dir] [out .mjs]
Needs numpy and scipy.
"""
import gzip, json, sys
from pathlib import Path
import numpy as np
from scipy.ndimage import binary_dilation, distance_transform_edt

ROOT = Path(__file__).resolve().parents[2]
CASE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'public/ct-data/s0019'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / 'src/eps/csp/csp-ct-geometry.mjs'
LEVELS = 21
SMOOTH = 2          # moving average half-width (levels) along the septal line


def load(case):
    meta = json.loads((case / 'meta.json').read_text())
    d = meta['dims']
    labels = np.frombuffer(gzip.decompress((case / 'labels.ctz').read_bytes()), np.uint8).reshape(d['z'], d['y'], d['x'])
    ids = {l['key']: l['id'] for l in meta['labels']}
    return meta, labels, ids


def mm(zyx, sp):
    """(z, y, x) voxel indices -> (x, y, z) millimetres."""
    z, y, x = np.asarray(zyx, float).T
    return np.stack([x * sp['x'], y * sp['y'], z * sp['z']], -1)


def main():
    meta, L, ids = load(CASE)
    sp = meta['spacingMm']
    rv, lv, ra, myo, ao = (L == ids[k] for k in ('rv', 'lv', 'ra', 'myocardium', 'aorta'))
    ball = np.ones((3, 3, 3), bool)

    tv_vox = np.argwhere(rv & binary_dilation(ra, ball, 2))
    tv = mm(tv_vox, sp).mean(0)
    rv_pts = mm(np.argwhere(rv), sp)
    caudal = rv_pts[rv_pts[:, 2] > tv[2]]
    apex = caudal[np.argmax(np.linalg.norm(caudal - tv, axis=1))]
    av = mm(np.argwhere(ao & binary_dilation(lv, ball, 2)), sp).mean(0)

    # RV septal surface: RV voxels next to the (LV) myocardium, i.e. the RV side of the septum.
    surf = mm(np.argwhere(rv & binary_dilation(myo, ball, 2)), sp)
    his = surf[np.argmin(np.linalg.norm(surf - av, axis=1))]

    # LV cavity distance map (mm) and nearest-voxel indices, for the LV side of the septum.
    dist, near = distance_transform_edt(~lv, sampling=(sp['z'], sp['y'], sp['x']), return_indices=True)
    rv_side, lv_side = [], []
    for t in np.linspace(0, 1, LEVELS):
        q = his + (apex - his) * t
        p = surf[np.argmin(np.linalg.norm(surf - q, axis=1))]
        rv_side.append(p)
        k = tuple(np.round([p[2] / sp['z'], p[1] / sp['y'], p[0] / sp['x']]).astype(int))
        lv_side.append(mm([near[:, k[0], k[1], k[2]]], sp)[0])
    rv_side, lv_side = np.array(rv_side), np.array(lv_side)

    def smooth(a):
        out = a.copy()
        for i in range(len(a)):
            lo, hi = max(0, i - SMOOTH), min(len(a), i + SMOOTH + 1)
            out[i] = a[lo:hi].mean(0)
        out[0], out[-1] = a[0], a[-1]
        return out
    rv_side, lv_side = smooth(rv_side), smooth(lv_side)
    thickness = np.linalg.norm(lv_side - rv_side, axis=1)

    ra_pts = mm(np.argwhere(ra), sp)
    ra_c = ra_pts.mean(0)
    top = ra_pts[ra_pts[:, 2] <= ra_pts[:, 2].min() + 4.5].mean(0)
    svc = top + np.array([0, 0, -25.0])
    high_svc = top + np.array([2, 2, -55.0])
    innominate = top + np.array([45, -8, -75.0])
    heart = np.isin(L, [ids[k] for k in ('lv', 'rv', 'la', 'ra')])
    iso = mm(np.argwhere(heart), sp).mean(0)

    r = lambda a: [round(float(v), 1) for v in a]
    geometry = {
        'case': meta['case'],
        'dims': meta['dims'], 'spacingMm': sp,
        'landmarks': {
            'iso': r(iso), 'his': r(his), 'apex': r(apex), 'tv': r(tv), 'av': r(av),
            'ra': r(ra_c), 'raTop': r(top), 'svc': r(svc), 'highSvc': r(high_svc), 'innominate': r(innominate),
            'septum': [{'level': round(float(t), 2), 'rv': r(a), 'lv': r(b)} for t, a, b in zip(np.linspace(0, 1, LEVELS), rv_side, lv_side)],
        },
    }
    head = ('/* Generated by scripts/eps/prepare-csp-ct-geometry.py from the real chest CT of the cardiac CT\n'
            ' * studio (public/ct-data/s0019, TotalSegmentator dataset, CC BY 4.0); do not edit by hand.\n'
            ' * Millimetres in voxel order: x patient right -> left, y anterior -> posterior, z cranial -> caudal.\n'
            ' * septum: RV and LV sides of the interventricular septum from the His (0) to the RV apex (1). */\n')
    OUT.write_text(head + 'export const CT_GEOMETRY = Object.freeze(' + json.dumps(geometry, indent=1) + ');\n')
    print('his-apex mm', round(float(np.linalg.norm(apex - his)), 1), 'septum mm', np.round(thickness, 1).tolist())


if __name__ == '__main__':
    main()
