// Bakes the parts of the atlas conduction system that src/ecg/ecg-atlas-conduction.js does not
// carry (Bachmann's bundle centre line and its inferior limb, the moderator band, the papillary
// muscles and both ventricular apices) into src/eps/conduction-atlas-extras.js, in the same atlas
// frame (chamber bounds centred, longest side 3.3). The EPS conduction lesson reads both files.
// Run with the dev server up: node scripts/eps/bake-conduction-extras.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/yh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');

const APP = (process.env.APP_URL || 'http://127.0.0.1:5173').replace(/\/$/, '');
const OUT = path.join(__dirname, '../../src/eps/conduction-atlas-extras.js');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 900, height: 700 } });
  await page.goto(`${APP}/eps/?lang=tr`);
  const baked = await page.evaluate(async () => {
    const { createHeart } = await import('/src/heart.js');
    const host = document.createElement('div');
    host.style.cssText = 'position:fixed;left:0;top:0;width:800px;height:600px';
    document.body.append(host);
    const heart = createHeart(host);
    await heart.ready;
    const round = (v) => Math.round(v * 1000) / 1000;
    const vec = (p) => [round(p.x ?? p[0]), round(p.y ?? p[1]), round(p.z ?? p[2])];
    const out = {};
    // three.js classes come from the heart's own geometry (no bare 'three' import in the page).
    const centre = (test) => {
      let box = null;
      heart.scene.updateMatrixWorld(true);
      heart.scene.traverse((o) => {
        if (!o.isMesh || !test(o)) return;
        o.geometry.computeBoundingBox();
        const b = o.geometry.boundingBox.clone().applyMatrix4(o.matrixWorld);
        box = box ? box.union(b) : b;
      });
      return box ? vec(box.getCenter(box.min.clone())) : null;
    };
    heart.scene.traverse((o) => {
      if (o.userData?.id === 'bachmann' && o.userData.path && !out.bachmann) {
        out.bachmann = o.userData.path.map(vec);
        out.bachmannInferior = (o.userData.inferiorLimb || []).map(vec);
      }
    });
    out.moderatorBand = centre((o) => o.userData?.id === 'moderator-band');
    out.rvAnteriorPapillary = centre((o) => /anterior papillary/i.test(o.name) && o.userData?.id === 'rv-papillary');
    out.lvPapillary = centre((o) => o.userData?.id === 'lv-papillary');
    out.raCentre = centre((o) => o.userData?.id === 'ra' && o.userData?.layer === 'chambers');
    out.laCentre = centre((o) => o.userData?.id === 'la' && o.userData?.layer === 'chambers');
    out.rvCentre = centre((o) => o.userData?.id === 'rv' && o.userData?.layer === 'chambers');
    out.lvCentre = centre((o) => o.userData?.id === 'lv' && o.userData?.layer === 'chambers');
    return out;
  });
  await browser.close();
  const missing = ['bachmann', 'moderatorBand', 'rvAnteriorPapillary', 'lvPapillary', 'raCentre', 'laCentre', 'rvCentre', 'lvCentre'].filter((k) => !baked[k] || !baked[k].length);
  if (missing.length) throw new Error(`Not found on the atlas: ${missing.join(', ')}`);
  const body = Object.entries(baked).map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`).join(',\n');
  fs.writeFileSync(OUT, `// Generated by scripts/eps/bake-conduction-extras.cjs from heart.js (atlas frame: chamber bounds\n// centred, longest side 3.3). Do not edit by hand; bake again when the atlas anatomy moves.\nexport const ATLAS_CONDUCTION_EXTRAS = Object.freeze({\n${body}\n});\n`);
  console.log(`baked ${Object.keys(baked).length} parts -> ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });
