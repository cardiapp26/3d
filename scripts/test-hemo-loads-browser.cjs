const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/yh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const APP = (process.env.APP_URL || 'http://127.0.0.1:5173').replace(/\/$/, '');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${APP}/pathophysiology/index.html?lang=tr#loads`);
    await page.waitForSelector('.pathophys-loads-lab .hemo-loads');
    const click = sel => page.locator(sel).first().click();
    const systolic = page.locator('[data-lvf]');
    const metric = async key => Number(await systolic.locator(`[data-lvf-metric="${key}"]`).getAttribute('data-value'));
    const baseline = { edv: await metric('edv'), sv: await metric('sv'), ef: await metric('ef'), stress: await metric('stress') };
    await click('[data-lvf-case=preload]');
    assert.ok(await metric('edv') > baseline.edv && await metric('sv') > baseline.sv);
    await click('[data-lvf-case=afterload]');
    assert.equal(await metric('edv'), baseline.edv);
    assert.ok(await metric('sv') < baseline.sv && await metric('ef') < baseline.ef, 'EF falls at fixed contractility');
    await click('[data-lvf-case=contractility]');
    assert.ok(await metric('sv') > baseline.sv);
    const reference = systolic.locator('[data-lvf-reference]');
    const outline = await reference.getAttribute('d');
    await click('[data-lvf-case=geometry]');
    assert.equal(await metric('ef'), baseline.ef);
    assert.ok(await metric('stress') > baseline.stress);
    assert.notEqual(await reference.getAttribute('d'), outline, 'geometry changes the section at fixed volume');
    for (const [phase, step] of [['0.46', '1'], ['0.49', '2'], ['0.64', '3'], ['0.94', '4']]) {
      await systolic.locator('[data-cycle-scrub]').fill(phase);
      await page.waitForFunction(value => document.querySelector('[data-lvf]').dataset.lvfStep === value, step);
    }
    const scrub = systolic.locator('[data-cycle-scrub]');
    await scrub.press('End');
    assert.equal(await scrub.inputValue(), '0.995');
    await page.waitForFunction(() => document.querySelector('[data-lvf]').dataset.lvfStep === '4');
    assert.equal(await systolic.locator('[data-motion-toggle]').getAttribute('aria-pressed'), 'false', 'scrubbing pauses the beat');
    const stress = async () => Number(await page.locator('[data-load-stress]').getAttribute('data-load-stress'));
    assert.equal(await stress(), 15);
    assert.equal(await page.locator('.load-scene').isVisible(), true, 'animated LV section is shown');
    assert.equal(await page.locator('.load-muscle').isVisible(), true, 'muscle-strip analogy is shown');
    assert.equal(await page.locator('.load-formula').getAttribute('open'), null, 'formula starts folded away');
    const wallFill = () => page.locator('.load-scene circle').nth(0).getAttribute('fill');
    const phases = new Set();
    for (let k = 0; k < 8; k++) { phases.add(await page.locator('.load-scene .scene-phase').textContent()); await page.waitForTimeout(450); }
    assert.ok(phases.size >= 3, `cycle animates through phases (${[...phases].join(', ')})`);
    assert.match(await wallFill(), /^rgb\(/, 'wall coloured by stress');
    await click('[data-load-case=dilation]'); assert.equal(await stress(), 20);
    await click('[data-load-mode=afterload]'); assert.equal(await stress(), 125);
    await click('[data-load-case=dilation]'); assert.equal(await stress(), 175);
    await click('[data-load-case=thickening]'); assert.ok(Math.abs(await stress() - 83.333333) < .001);
    await click('.load-reset'); assert.equal(await stress(), 125);
    const pressure = page.locator('[data-load-param=p]');
    await pressure.focus(); await page.keyboard.press('ArrowRight');
    assert.equal(await pressure.inputValue(), '125'); assert.ok(await stress() > 125, 'keyboard changes pressure and calculated stress');
    await click('[data-load-mode=preload]'); assert.equal(await stress(), 20, 'each phase keeps its own values');
    await click('[data-pathophys-lang=en]');
    assert.equal(await stress(), 20, 'language preserves numeric state');
    assert.match(await systolic.locator('h3').textContent(), /systolic performance/);
    assert.equal(await systolic.locator('[data-lvf-case=geometry]').getAttribute('aria-pressed'), 'true', 'language preserves comparison');
    assert.equal(await systolic.getAttribute('data-lvf-step'), '4', 'language preserves the selected phase');
    assert.match(await page.locator('.load-definition').textContent(), /before contraction/, 'definition switches to English');
    await click('[data-station=pv-loop]'); await page.waitForSelector('.pathophys-pv-svg');
    await click('[data-station=loads]'); await page.waitForSelector('.hemo-loads');
    assert.equal(await stress(), 15, 'station switch rebuilds the explorer at baseline');
    const shots = process.env.SHOT_DIR || '/private/tmp/cardia-loads-shots'; fs.mkdirSync(shots, { recursive: true });
    await page.locator('.hemo-loads').screenshot({ path: `${shots}/loads-desktop.png` });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.hemo-loads').scrollIntoViewIfNeeded();
    const bounds = await page.locator('.hemo-loads').evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
    assert.ok(bounds.scroll <= bounds.width + 1, 'no explorer horizontal overflow on mobile');
    await click('[data-load-mode=afterload]'); await click('[data-load-case=pressure]'); assert.equal(await stress(), 187.5);
    await page.locator('.hemo-loads').screenshot({ path: `${shots}/loads-mobile.png` });
    const systolicBounds = await systolic.evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
    assert.ok(systolicBounds.scroll <= systolicBounds.width + 1, 'no systolic lesson overflow on mobile');
    assert.deepEqual(errors, []);
    console.log('PASS: Pathophysiology LV function and load explorer: calcium phases, pump determinants, controls, language, station switch, mobile, no page errors');
    console.log(`Screenshots: ${shots}`);
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
