const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/yh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const APP = (process.env.APP_URL || 'http://127.0.0.1:5189').replace(/\/$/, '');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(`${APP}/pharmacology/?lang=tr#/antiarrhythmics`);
    await page.locator('.phys-guide').waitFor({state:'visible'});
    await page.locator('.pharmaep-cells button').first().click();
    await page.locator('.pharmaep-phases [data-phase="2"]').click();
    assert.equal(await page.locator('.phys-currents').isVisible(),true);
    assert.equal(await page.locator('.phys-currents .phys-line').count(),3);
    await page.locator('[data-phys-control=step-3]').click();
    assert.equal(await page.locator('[data-phys-control=step-3]').evaluate(el=>el===document.activeElement),true,'step change retains keyboard focus');
    assert.match(await page.locator('.phys-explain').textContent(),/SERCA/);
    await page.locator('[data-phys-control=step-4]').click();
    assert.match(await page.locator('.phys-explain').textContent(),/3 Na/);
    await page.locator('[data-phys-topic=conduction]').click();
    await page.locator('[data-phys-control=step-3]').click();
    assert.match(await page.locator('.phys-explain').textContent(),/PA\/AH\/HV/);
    await page.locator('[data-pharma-lang=en]').click();
    assert.equal(await page.locator('[data-phys-topic=conduction]').getAttribute('aria-pressed'),'true');
    assert.match(await page.locator('.phys-explain').textContent(),/cumulative/);
    const shots=process.env.SHOT_DIR||'/private/tmp/cardia-physiology-shots';fs.mkdirSync(shots,{recursive:true});
    await page.locator('[data-phys-topic=calcium]').click();
    await page.locator('.phys-guide').screenshot({path:`${shots}/calcium.png`});
    await page.setViewportSize({width:390,height:844});
    await page.locator('.phys-guide').scrollIntoViewIfNeeded();
    const overflow=async()=>page.locator('.phys-guide').evaluate(el=>el.scrollWidth>el.clientWidth+1);
    assert.equal(await overflow(),false,'pharmacology guide mobile overflow');
    await page.goto(`${APP}/?lang=tr`);
    await page.waitForSelector('#viewport[data-model-ready=true]');
    await page.locator('[data-mode=cath]:not([data-mode-step])').dispatchEvent('click');
    await page.locator('[data-hemo-view=physiology]').click();
    assert.equal(await page.locator('.hemo-metrics').isVisible(),false);
    const slide=async(key,v)=>page.locator(`[data-phys-param=${key}]`).evaluate((el,v)=>{el.value=v;el.dispatchEvent(new Event('input',{bubbles:true}));},String(v));
    await slide('filling',4); const before=await page.locator('.phys-output').textContent();
    await slide('filling',8); assert.notEqual(await page.locator('.phys-output').textContent(),before);
    await page.locator('[data-phys-control=tone]').click();
    await page.locator('[data-phys-control=sympathetic]').click();
    assert.equal(await page.locator('[data-phys-control=sympathetic]').evaluate(el=>el===document.activeElement),true,'tone change retains keyboard focus');
    assert.equal(await page.locator('[data-phys-control=sympathetic]').getAttribute('aria-pressed'),'true');
    await page.locator('[data-phys-control=pressure]').click(); await slide('arterial',220);
    await page.locator('[data-phys-topic=pv]').click(); await page.locator('[data-phys-control=step-4]').click();
    assert.equal(await page.locator('.phys-pe').count(),1); assert.match(await page.locator('.phys-explain').textContent(),/PVA/);
    await page.locator('.phys-guide').screenshot({path:`${shots}/pv-mobile.png`});
    await page.locator('[data-phys-topic=wiggers]').click(); await slide('cycle',60);
    assert.equal(await page.locator('.phys-lane').count(),3);
    await page.locator('[data-phys-control=afib]').click();
    assert.equal(await page.locator('.phys-optional').count(),1,'AF removes S4, keeps optional S3');
    await page.locator('#lang-btn').dispatchEvent('click');
    assert.equal(await page.locator('[data-phys-topic=wiggers]').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('[data-phys-param=cycle]').inputValue(),'60');
    assert.equal(await overflow(),false,'hemodynamics guide mobile overflow');
    await page.locator('.phys-guide').screenshot({path:`${shots}/wiggers-mobile.png`});
    await page.locator('[data-hemo-view=pv]').click(); assert.equal(await page.locator('.hemo-metrics').isVisible(),true);
    assert.deepEqual(errors,[]);
    console.log('PASS physiology browser: ionic phase panel, calcium steps, conduction, pump modes/sliders, PV energy, Wiggers/AF, language retention, mobile');
    console.log(`Screenshots: ${shots}`);
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
