// Bakes the conduction system that heart.js measures on the atlas (SA and AV nodes, His, both
// bundles, the fascicles and the Purkinje branches) into src/ecg/ecg-atlas-conduction.js, so the
// ECG chapter labs can draw it on the same atlas without loading the whole anatomy viewer.
// Run with the dev server up: node scripts/ecg/bake-atlas-conduction.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/yh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');

const APP = (process.env.APP_URL || 'http://127.0.0.1:5173').replace(/\/$/, '');
const OUT = path.join(__dirname, '../../src/ecg/ecg-atlas-conduction.js');
const KEYS = {
  'Sinoatrial node': 'sa', 'Atrioventricular node': 'avn',
  'Bundle of His': 'his', 'Right bundle branch': 'rbb', 'Left bundle branch trunk': 'lbb',
  'LBB Anterior fascicle': 'laf', 'LBB Posterior fascicle': 'lpf',
  'Purkinje network branch 1': 'purkinjeRv', 'Purkinje network branch 2': 'purkinjeLaf', 'Purkinje network branch 3': 'purkinjeLpf',
  'Anterior internodal tract': 'tractAnterior', 'Middle internodal tract (Wenckebach)': 'tractMiddle', 'Posterior internodal tract (Thorel)': 'tractPosterior'
};

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 900, height: 700 } });
  await page.goto(`${APP}/ecg/?lang=tr`);
  const baked = await page.evaluate(async (keys) => {
    const { createHeart } = await import('/src/heart.js');
    const host = document.createElement('div');
    host.style.cssText = 'position:fixed;left:0;top:0;width:800px;height:600px';
    document.body.append(host);
    const heart = createHeart(host);
    await heart.ready;
    const out = {}, round = v => Math.round(v * 1000) / 1000;
    heart.scene.traverse(o => {
      const key = keys[o.name];
      if (!key || out[key]) return;
      const pts = o.geometry?.parameters?.path?.points;
      out[key] = pts ? pts.map(p => [round(p.x), round(p.y), round(p.z)]) : [round(o.position.x), round(o.position.y), round(o.position.z)];
    });
    return out;
  }, KEYS);
  await browser.close();
  const missing = Object.values(KEYS).filter(k => !baked[k]);
  if (missing.length) throw new Error(`Not found on the atlas: ${missing.join(', ')}`);
  const body = Object.entries(baked).map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`).join(',\n');
  fs.writeFileSync(OUT, `// Generated by scripts/ecg/bake-atlas-conduction.cjs from heart.js (atlas frame: chamber bounds\n// centred, longest side 3.3). Do not edit by hand; bake again when the conduction system moves.\nexport const ATLAS_CONDUCTION = Object.freeze({\n${body}\n});\n`);
  console.log(`baked ${Object.keys(baked).length} parts -> ${path.relative(process.cwd(), OUT)}`);
})().catch(e => { console.error(e); process.exit(1); });
